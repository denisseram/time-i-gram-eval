#!/usr/bin/env python3
"""Effort measures per run (tidy CSV) and their summary statistics. Does not run any agent.

  python3 scripts/effort_stats.py   -> results/effort_per_run.csv, results/effort_summary.md

Sources: results/scores.csv (written by `score.py summary`: final scores, deliverable size, turns, ...) and
results/metrics.csv (token counts incl. cache, from each run's meta.json). The deliverable size is recomputed
from runs/ with score.py's own measure and must equal the stored value; the overall medians must equal the
ones in results/summary.md. Either mismatch stops the script.
"""
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import score  # noqa: E402  (deliverable_size, DELIVERABLE, run_dir_of)

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
TOOLS = ["d3", "vega-lite", "ggtime", "time-i-gram"]
TOOL_LABEL = {"d3": "D3", "vega-lite": "Vega-Lite", "ggtime": "ggtime", "time-i-gram": "time-i-gram"}
TASKS = ["E1", "E2", "E3", "E4", "E5"]

# column -> (label, decimals)
MEASURES = {
    "spec_chars": ("Specification size (characters, no comments or extra whitespace)", 0),
    "output_tokens": ("Output tokens", 0),
    "input_tokens_total": ("Input tokens (uncached + cache read + cache creation)", 0),
    "wall_min": ("Wall time (min)", 1),
    "turns": ("Turns", 1),
    "tool_calls": ("Tool calls", 1),
    "self_check_renders": ("Self-check renders", 1),
    "score_pct": ("Rubric score (% of points)", 1),
}


def build():
    s = pd.read_csv(RES / "scores.csv", dtype={"repeat": str})
    m = pd.read_csv(RES / "metrics.csv")
    df = s.merge(m[["run_id", "cache_read_tokens", "cache_creation_tokens"]], on="run_id", how="left",
                 validate="one_to_one")

    # deliverable size: recompute with the same measure as the draft and require equality
    recomputed = []
    for run_id, tool in zip(df.run_id, df.tool):
        path = score.run_dir_of(run_id) / score.DELIVERABLE[tool]
        recomputed.append(score.deliverable_size(path)[1] if path.exists() else np.nan)
    bad = df.run_id[np.array(recomputed) != df.deliverable_chars.to_numpy()]
    if len(bad):
        sys.exit(f"deliverable_chars in scores.csv differs from runs/ for: {', '.join(bad)}")

    out = pd.DataFrame({
        "run_id": df.run_id, "task": df.example, "tool": df.tool, "repeat": df["repeat"].astype(int),
        "spec_chars": df.deliverable_chars,
        "output_tokens": df.output_tokens,
        "input_tokens_uncached": df.input_tokens,
        "cache_read_tokens": df.cache_read_tokens,
        "cache_creation_tokens": df.cache_creation_tokens,
        "input_tokens_total": df.input_tokens + df.cache_read_tokens + df.cache_creation_tokens,
        "wall_min": (df.wall_seconds / 60).round(3),
        "turns": df.agent_turns, "tool_calls": df.tool_calls, "self_check_renders": df.self_renders,
        "score_sum": df.score_sum, "score_max": df.score_max,
        "score_pct": (100 * df.score_sum / df.score_max).round(2),
    })
    out["tool"] = pd.Categorical(out.tool, TOOLS, ordered=True)
    out = out.sort_values(["task", "tool", "repeat"]).reset_index(drop=True)
    return out


def check_against_draft(df):
    """Every median in the 'Effort per run' table of results/summary.md must be reproduced."""
    text = (RES / "summary.md").read_text()
    col_of = {"Wall time (min)": ("wall_min", 1), "Turns": ("turns", 0), "Tool calls": ("tool_calls", 0),
              "Self-checks with render": ("self_check_renders", 0), "Output tokens": ("output_tokens", 0),
              "Deliverable size (characters, no comments or extra whitespace)": ("spec_chars", 0)}
    mismatches, checked = [], []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip("|").split("|")]
        if cells[0] in col_of:
            col, d = col_of[cells[0]]
            for tool, draft in zip(TOOLS, cells[1:]):
                ours = round(float(df.loc[df.tool == tool, col].median()), d)
                checked.append((cells[0], tool, draft, ours))
                if abs(ours - float(draft)) > 1e-9:
                    mismatches.append((cells[0], tool, draft, ours))
    return checked, mismatches


def fmt(x, d):
    if pd.isna(x):
        return "–"
    return f"{x:,.{d}f}"


def tables(df):
    tl = [TOOL_LABEL[t] for t in TOOLS]
    out = ["# Effort per run: summary statistics", "",
           "Generated by `python3 scripts/effort_stats.py` from `results/effort_per_run.csv` "
           f"({len(df)} runs: {df.task.nunique()} tasks × {df.tool.nunique()} tools × "
           f"{df.groupby(['task', 'tool'], observed=True).size().max()} repeats). No agent was re-run.", "",
           "SD is the sample standard deviation (n − 1). Q1/Q3 are linear-interpolation quartiles "
           "(numpy default). Input tokens are the sum of uncached input, cache reads and cache creation "
           "(the parts are separate columns in the CSV). Wall time is the agent session, rendering excluded. "
           "Rubric score = score_sum / score_max of the final human scores.", ""]
    for col, (label, d) in MEASURES.items():
        g = df.groupby("tool", observed=True)[col]
        out += [f"## {label}", "", "### Overall per tool", "",
                "| Statistic | " + " | ".join(tl) + " |", "|---|" + "---:|" * len(tl)]
        stats = {"n": g.count(), "mean": g.mean(), "SD": g.std(ddof=1), "median": g.median(),
                 "Q1": g.quantile(.25), "Q3": g.quantile(.75), "min": g.min(), "max": g.max()}
        for name, ser in stats.items():
            if name == "Q3":
                continue
            if name == "Q1":
                cells = [f"{fmt(stats['Q1'][t], d)} – {fmt(stats['Q3'][t], d)}" for t in TOOLS]
                name = "IQR (Q1 – Q3)"
            else:
                cells = [fmt(ser[t], 0 if name == "n" else d) for t in TOOLS]
            out.append(f"| {name} | " + " | ".join(cells) + " |")
        out += ["", "### Per task × tool (n = runs; mean / median / min – max)", "",
                "| Task | " + " | ".join(tl) + " |", "|---|" + "---:|" * len(tl)]
        gt = df.groupby(["task", "tool"], observed=True)[col]
        n, mean, med, lo, hi = gt.count(), gt.mean(), gt.median(), gt.min(), gt.max()
        for task in TASKS:
            cells = [f"n={n[task, t]}: {fmt(mean[task, t], d)} / {fmt(med[task, t], d)} / "
                     f"{fmt(lo[task, t], d)} – {fmt(hi[task, t], d)}" for t in TOOLS]
            out.append(f"| {task} | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def main():
    df = build()
    missing = {c: df.run_id[df[c].isna()].tolist() for c in df.columns if df[c].isna().any()}
    if missing:
        print("Missing values (not imputed):", missing)
    else:
        print(f"{len(df)} runs, no missing values in any measure.")
    checked, mismatches = check_against_draft(df)
    if mismatches:
        for m in mismatches:
            print("MISMATCH with results/summary.md:", m)
        sys.exit(1)
    print(f"All {len(checked)} medians of results/summary.md reproduced.")
    df.to_csv(RES / "effort_per_run.csv", index=False)
    (RES / "effort_summary.md").write_text(tables(df))
    print("Wrote results/effort_per_run.csv and results/effort_summary.md")


if __name__ == "__main__":
    main()
